import {
  BatteryCharging,
  Bike,
  CircleDot,
  ClipboardCheck,
  CreditCard,
  Disc,
  Droplet,
  FileText,
  Filter,
  Fuel,
  IdCard,
  Landmark,
  MapPin,
  Package,
  Store,
  Link,
  Link2,
  MoveVertical,
  Shield,
  ShieldCheck,
  SprayCan,
  Wind,
  Wrench,
  Zap,
  type LucideIcon,
} from "lucide-react";

const MAPA: Record<string, LucideIcon> = {
  BatteryCharging,
  Bike,
  CircleDot,
  ClipboardCheck,
  CreditCard,
  Disc,
  Droplet,
  FileText,
  Filter,
  Fuel,
  IdCard,
  Landmark,
  MapPin,
  Package,
  Store,
  Link,
  Link2,
  MoveVertical,
  Shield,
  ShieldCheck,
  SprayCan,
  Wind,
  Wrench,
  Zap,
};

export function Icono({ nombre, size = 18, className }: { nombre: string; size?: number; className?: string }) {
  const C = MAPA[nombre] ?? Wrench;
  return <C size={size} className={className} />;
}
